import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import resolveActiveLockfile from "../src/lockfiles/index.js";
import parseNpmLockfile from "../src/lockfiles/npm.js";
import parsePnpmLockfile from "../src/lockfiles/pnpm.js";
import parseYarnLockfile from "../src/lockfiles/yarn.js";
import parseBunLockfile, { parseBunBinaryLockfile } from "../src/lockfiles/bun.js";
import { UnsupportedLockfileError } from "../src/lockfiles/shared.js";

const fixture = (...segments) =>
  fs.readFileSync(path.join(import.meta.dirname, "fixtures", ...segments), "utf8");

function projectWith(t, fileNames) {
  const projectRoot = fs.mkdtempSync(path.join(os.tmpdir(), "deeval-"));
  t.after(() => fs.rmSync(projectRoot, { recursive: true, force: true }));
  for (const fileName of fileNames) {
    fs.writeFileSync(path.join(projectRoot, fileName), "");
  }
  return projectRoot;
}

// The *-basic fixtures were generated by the real package managers from the
// same package.json, so they all normalize to this map.
const BASIC_DEPENDENCIES = new Map([
  ["ms", { specifier: "^2.1.3", version: "2.1.3" }],
  ["kleur", { specifier: "^4.1.5", version: "4.1.5" }],
  ["picocolors", { specifier: "^1.1.1", version: "1.1.1" }],
]);

/** @type {[string, Function, string, string][]} */
const parsers = [
  ["npm v3", parseNpmLockfile, "npm-basic", "package-lock.json"],
  ["pnpm v9", parsePnpmLockfile, "pnpm-basic", "pnpm-lock.yaml"],
  ["pnpm v6", parsePnpmLockfile, "pnpm8-basic", "pnpm-lock.yaml"],
  ["yarn berry", parseYarnLockfile, "yarn-basic", "yarn.lock"],
  ["bun text", parseBunLockfile, "bun-basic", "bun.lock"],
];

for (const [label, parse, fixtureName, lockfileName] of parsers) {
  test(`${label} lockfile normalizes to name → { specifier, version }`, () => {
    const parsed = parse(fixture(fixtureName, lockfileName), lockfileName);
    if (fixtureName === "pnpm-basic") {
      assert.deepEqual(
        parsed,
        new Map([["yaml", { specifier: "^2.9.1", version: "2.9.1" }]]),
      );
    } else {
      assert.deepEqual(parsed, BASIC_DEPENDENCIES);
    }
  });
}

/** @type {[string, () => unknown][]} */
const unsupported = [
  ["npm lockfileVersion 1", () => parseNpmLockfile(fixture("npm-v1", "package-lock.json"), "package-lock.json")],
  ["yarn classic", () => parseYarnLockfile(fixture("yarn-classic", "yarn.lock"), "yarn.lock")],
  ["pnpm lockfileVersion 5.4", () => parsePnpmLockfile("lockfileVersion: 5.4\n", "pnpm-lock.yaml")],
  ["bun.lockb", () => parseBunBinaryLockfile()],
];

for (const [label, parse] of unsupported) {
  test(`${label} is rejected as unsupported with a suggestion`, () => {
    assert.throws(parse, (err) => {
      assert.ok(err instanceof UnsupportedLockfileError);
      assert.ok(err.suggestion);
      return true;
    });
  });
}

test("yarn keeps npm: aliases but strips npm: from plain ranges", () => {
  const lockfile = `
"real-pkg@npm:^1.0.0":
  version: 1.2.0

"ms@npm:^2.1.3":
  version: 2.1.3

"root@workspace:.":
  version: 0.0.0-use.local
  dependencies:
    alias: "npm:real-pkg@^1.0.0"
    ms: "npm:^2.1.3"
`;
  assert.deepEqual(
    parseYarnLockfile(lockfile, "yarn.lock"),
    new Map([
      ["alias", { specifier: "npm:real-pkg@^1.0.0", version: undefined }],
      ["ms", { specifier: "^2.1.3", version: "2.1.3" }],
    ]),
  );
});

test("bun reads versions of scoped packages", () => {
  const lockfile = `{
  "workspaces": { "": { "dependencies": { "@scope/pkg": "^1.0.0", }, }, },
  "packages": { "@scope/pkg": ["@scope/pkg@1.4.0", "", {}, "sha512-x"], },
}`;
  assert.deepEqual(
    parseBunLockfile(lockfile),
    new Map([["@scope/pkg", { specifier: "^1.0.0", version: "1.4.0" }]]),
  );
});

test("malformed pnpm YAML throws instead of returning partial data", () => {
  assert.throws(() => parsePnpmLockfile("importers: [unclosed\n", "pnpm-lock.yaml"));
});

test("picks the only present lockfile", (t) => {
  const result = resolveActiveLockfile(projectWith(t, ["pnpm-lock.yaml"]), {});
  assert.equal(result.lockfile.lockfileName, "pnpm-lock.yaml");
  assert.equal(result.packageManager, "pnpm");
  assert.deepEqual(result.findings, []);
});

test("prefers package-lock.json and warns when several are present", (t) => {
  const result = resolveActiveLockfile(
    projectWith(t, ["pnpm-lock.yaml", "package-lock.json"]),
    {},
  );
  assert.equal(result.lockfile.lockfileName, "package-lock.json");
  assert.deepEqual(
    result.findings.map(({ code }) => code),
    ["LOCKFILE_MULTIPLE"],
  );
});

test("the packageManager field picks the lockfile when several are present", (t) => {
  const result = resolveActiveLockfile(
    projectWith(t, ["pnpm-lock.yaml", "package-lock.json"]),
    { packageManager: "pnpm@9.15.0+sha512.abc" },
  );
  assert.equal(result.lockfile.lockfileName, "pnpm-lock.yaml");
  assert.equal(result.packageManager, "pnpm");
});

test("a lockfile of another package manager than packageManager is a warning", (t) => {
  const result = resolveActiveLockfile(projectWith(t, ["package-lock.json"]), {
    packageManager: "bun@1.4.2",
  });
  assert.equal(result.packageManager, "bun");
  assert.deepEqual(
    result.findings.map(({ code }) => code),
    ["LOCKFILE_PACKAGE_MANAGER_MISMATCH"],
  );
});

test("missing lockfile suggests the declared package manager", (t) => {
  const result = resolveActiveLockfile(projectWith(t, []), {
    packageManager: "yarn@4.9.2",
  });
  assert.equal(result.lockfile, undefined);
  assert.equal(result.findings[0].code, "LOCKFILE_MISSING");
  assert.match(result.findings[0].suggestion, /`yarn install`/);
});

test("unknown packageManager values are ignored", (t) => {
  const result = resolveActiveLockfile(projectWith(t, ["bun.lock"]), {
    packageManager: "deno@2.0.0",
  });
  assert.equal(result.packageManager, "bun");
  assert.deepEqual(result.findings, []);
});
